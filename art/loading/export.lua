local source=app.open('art/loading/loading-cat.aseprite')
assert(source.width==32 and source.height==32 and #source.frames==23)
local timings={210,211,210,211,211,147,63,77,134,211,210,211,134,76,24,140,47,53,158,210,211,71,140}
local atlas=Image(32*#source.frames,32,ColorMode.RGB)
local total=0
local first
for i,frame in ipairs(source.frames) do
 assert(math.abs(frame.duration*1000-timings[i])<0.01,'Approved timing changed')
 total=total+timings[i]
 local image=Image(32,32,ColorMode.RGB)
 for _,layer in ipairs(source.layers) do
  local cel=layer:cel(i)
  if cel then image:drawImage(cel.image,cel.position) end
 end
 if not first then first=Image(image) end
 for y=8,23 do for x=8,23 do
  if y<16 or y>17 or x<12 or x>19 then
   assert(image:getPixel(x,y)==first:getPixel(x,y),'Head moved outside eye region')
  end
 end end
 atlas:drawImage(image,Point((i-1)*32,0))
end
assert(total==3370)
atlas:saveAs('src/assets/loading-cat.png')
local saved=Image{fromFile='src/assets/loading-cat.png'}
for y=0,31 do for x=0,735 do assert(saved:getPixel(x,y)==atlas:getPixel(x,y)) end end
local css=assert(io.open('src/loading.css','w'))
css:write('/* Generated by art/loading/export.lua from the approved Aseprite animation. */\n')
css:write('.loading-cat { display: block; width: 128px; height: 128px; flex-shrink: 0; background: url("./assets/loading-cat.png") 0 0 / 2944px 128px no-repeat; image-rendering: pixelated; animation: loading-cat 3370ms step-end infinite; animation-play-state: var(--loading-animation-state, running); }\n')
css:write('@keyframes loading-cat {\n')
local elapsed=0
for i,ms in ipairs(timings) do
 css:write(string.format('  %.6f%% { background-position: %dpx 0; }\n',elapsed/total*100,-(i-1)*128))
 elapsed=elapsed+ms
end
css:write('  100% { background-position: 0 0; }\n}\n')
css:close()
print('Verified approved 23-frame, 3370ms PNG atlas and generated matching CSS. No GIF runtime.')
