local source=app.open('art/login/login-window.aseprite')
assert(source.width==128 and source.height==112 and #source.frames==8)
local timings={900,600,450,450,100,140,100,850}
local atlas=Image(1024,112,ColorMode.RGB)
local first
local total=0
for i,frame in ipairs(source.frames) do
 assert(math.abs(frame.duration*1000-timings[i])<0.01,'Approved timing changed')
 total=total+timings[i]
 local im=Image(128,112,ColorMode.RGB)
 for _,layer in ipairs(source.layers) do
  local cel=layer:cel(i)
  if cel then im:drawImage(cel.image,cel.position) end
 end
 if not first then first=Image(im) end
 for y=0,111 do for x=0,127 do
  if x<47 or x>=79 or y<52 or y>=85 then assert(im:getPixel(x,y)==first:getPixel(x,y),'Only the cat may animate') end
 end end
 atlas:drawImage(im,Point((i-1)*128,0))
end
assert(total==3590)
atlas:saveAs('src/assets/login-window.png')
local saved=Image{fromFile='src/assets/login-window.png'}
for y=0,111 do for x=0,1023 do assert(saved:getPixel(x,y)==atlas:getPixel(x,y)) end end
local css=assert(io.open('src/screens/login-scene.css','w'))
css:write('/* Generated by art/login/export.lua from the owner-approved Aseprite scene. */\n')
css:write('.login-scene { background: url("../assets/login-window.png") 0 0 / 800% 100% no-repeat; image-rendering: pixelated; animation: login-window 3590ms step-end infinite; animation-play-state: var(--loading-animation-state, running); }\n')
css:write('@keyframes login-window {\n')
local elapsed=0
for i,ms in ipairs(timings) do
 css:write(string.format('  %.6f%% { background-position: %.6f%% 0; }\n',elapsed/total*100,(i-1)/7*100))
 elapsed=elapsed+ms
end
css:write('  100% { background-position: 0% 0; }\n}\n');css:close()
print('Verified approved 8-frame, 3590ms login atlas; only the cat animates. PNG and matching CSS exported.')
