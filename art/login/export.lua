local output=assert(app.params['output'],'Supply --script-param output=<folder>; this exporter does not choose a deployment path')
local source=app.open('art/login/login-window.aseprite')
assert(source.width==128 and source.height==112 and #source.frames==32)
local timings={900,200,80,120,80,120,450,450,100,140,100,850,900,10,200,200,190,10,440,450,100,140,100,850,900,600,450,450,100,140,100,850}
local atlas=Image(4096,112,ColorMode.RGB)
local first
local total=0
for i,frame in ipairs(source.frames) do
 assert(math.abs(frame.duration*1000-timings[i])<0.01,'Approved timing changed')
 total=total+timings[i]
 local im=Image(128,112,ColorMode.RGB)
 for _,layer in ipairs(source.layers) do
  local cel=layer:cel(i)
  if cel then im:drawImage(cel.image,cel.position) end
 end
 if not first then first=Image(im) end
 for y=0,111 do for x=0,127 do
  local cat=x>=47 and x<85 and y>=44 and y<87
  local leaf=(x>=93 and x<=100 and y>=71 and y<=74) or (x>=104 and x<=111 and y>=67 and y<=70) or (x>=99 and x<=104 and y>=63 and y<=66)
  if not cat and not leaf then assert(im:getPixel(x,y)==first:getPixel(x,y),'Scene moved outside cat and leaves') end
  if x>=53 and x<=70 and y>=83 and y<=86 then assert(im:getPixel(x,y)==first:getPixel(x,y),'Cat paws lost their anchor') end
 end end
 atlas:drawImage(im,Point((i-1)*128,0))
end
assert(total==10770)
atlas:saveAs(output..'/login-window.png')
local saved=Image{fromFile=output..'/login-window.png'}
for y=0,111 do for x=0,4095 do assert(saved:getPixel(x,y)==atlas:getPixel(x,y)) end end
local css=assert(io.open(output..'/login-scene.css','w'))
css:write('/* Generated by art/login/export.lua from the owner-approved Aseprite scene. */\n')
css:write('.login-scene { background: url("../assets/login-window.png") 0 0 / 3200% 100% no-repeat; image-rendering: pixelated; animation: login-window 10770ms step-end infinite; animation-play-state: var(--loading-animation-state, running); }\n')
css:write('@keyframes login-window {\n')
local elapsed=0
for i,ms in ipairs(timings) do
 css:write(string.format('  %.6f%% { background-position: %.6f%% 0; }\n',elapsed/total*100,(i-1)/31*100))
 elapsed=elapsed+ms
end
css:write('  100% { background-position: 0% 0; }\n}\n');css:close()
print('Verified approved 32-frame, 10770ms login atlas; only the cat and leaves animate. PNG and matching CSS exported.')
